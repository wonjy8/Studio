import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createApp} from '../server/index.js';
import {hashPassword,digest} from '../server/auth.js';
import {openStore} from '../server/store.js';
test('admin-only invitations, atomic signup, expiry, revocation and account isolation',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'studio-invites-')),origin='http://localhost';
 const {server,db}=await createApp({dir,origin,secure:false});
 for(const name of ['owner','member'])db.prepare('INSERT INTO users VALUES(?,?,?)').run(name,name,await hashPassword('Fictional!8'));
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});});
 const base=`http://127.0.0.1:${server.address().port}`;
 const call=(path,method='GET',body,cookie='',extra={})=>fetch(base+'/api/'+path,{method,headers:{Origin:origin,Cookie:cookie,'Content-Type':'application/json',...extra},body:body===undefined?undefined:JSON.stringify(body)});
 const login=async username=>{const r=await call('login','POST',{username,password:'Fictional!8'});assert.equal(r.status,200);return r.headers.get('set-cookie').split(';')[0];};
 assert.equal((await call('invitations','POST')).status,401);
 assert.equal((await call('signup','POST',{username:'open-user',password:'Fictional!8'})).status,400);
 const owner=await login('owner'),member=await login('member');
 assert.equal((await (await call('session','GET',undefined,owner)).json()).isAdmin,true);
 assert.equal((await (await call('session','GET',undefined,member)).json()).isAdmin,false);
 assert.equal((await call('invitations','POST',undefined,member)).status,403);
 assert.equal((await call('invitations','GET',undefined,member)).status,403);
 assert.equal((await call('invitations','POST',undefined,owner,{Origin:'https://attacker.invalid'})).status,403);
 const invite=await (await call('invitations','POST',undefined,owner)).json();
 const raw=invite.url.split('#invite=')[1];
 assert.equal((await call('signup','POST',{token:raw,username:'signed-in-user',password:'Fictional!8'},owner)).status,409);assert.match(raw,/^[a-f0-9]{64}$/);
 assert.equal(db.prepare('SELECT token_hash FROM invitations WHERE id=?').get(invite.id).token_hash,digest(raw));
 assert.equal(JSON.stringify(await (await call('invitations','GET',undefined,owner)).json()).includes(raw),false);
 assert.equal((await call('signup','POST',{token:raw,username:'new-member',password:'weak'})).status,400);
 assert.equal((await call('signup','POST',{token:raw,username:'OWNER',password:'Fictional!8'})).status,409);
 assert.equal(db.prepare('SELECT used_at FROM invitations WHERE id=?').get(invite.id).used_at,null);
 const results=await Promise.all(['new-member','other-member'].map(username=>call('signup','POST',{token:raw,username,name:'Fictional Registered Name',password:'Fictional!8',isAdmin:true})));
 assert.deepEqual(results.map(r=>r.status).sort(),[201,400]);
 assert.equal(db.prepare("SELECT name FROM account_profiles").get().name,'Fictional Registered Name');
 const name=db.prepare("SELECT username FROM users WHERE username IN ('new-member','other-member')").get().username;
 const joined=await login(name);
 assert.equal((await (await call('session','GET',undefined,joined)).json()).isAdmin,false);
 assert.equal((await (await call('workspace','GET',undefined,joined)).json()).state,null);
 assert.equal((await call('invitations','POST',undefined,joined)).status,403);
 const make=async()=>{const inv=await (await call('invitations','POST',undefined,owner)).json();return {...inv,token:inv.url.split('#invite=')[1]};};
 const revoked=await make();assert.equal((await call('invitations/'+revoked.id,'DELETE',undefined,member)).status,403);
 assert.equal((await call('invitations/'+revoked.id,'DELETE',undefined,owner)).status,200);
 assert.equal((await call('signup','POST',{token:revoked.token,username:'revoked-user',password:'Fictional!8'})).status,400);
 const expired=await make();db.prepare('UPDATE invitations SET expires=0 WHERE id=?').run(expired.id);
 assert.equal((await call('signup','POST',{token:expired.token,username:'expired-user',password:'Fictional!8'})).status,400);
 for(let i=0;i<20;i++)assert.equal((await call('invitations','POST',undefined,owner)).status,201);
 assert.equal((await call('invitations','POST',undefined,owner)).status,429);
});
test('upgrade preserves earliest retained login as administrator across restarts',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'studio-owner-'));
 let db=openStore(dir);
 for(const id of ['first-provisioned','first-login'])db.prepare('INSERT INTO users VALUES(?,?,?)').run(id,id,await hashPassword('Fictional!8'));
 db.prepare('INSERT INTO sessions VALUES(?,?,?)').run('fictional-digest','first-login',Date.now()+10000);db.close();
 db=openStore(dir);assert.equal(db.prepare("SELECT value FROM site_settings WHERE key='admin_user_id'").get().value,'first-login');db.prepare('DELETE FROM sessions').run();db.close();
 db=openStore(dir);assert.equal(db.prepare("SELECT value FROM site_settings WHERE key='admin_user_id'").get().value,'first-login');db.close();await rm(dir,{recursive:true,force:true});
});
