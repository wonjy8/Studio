import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createApp} from '../server/index.js';
import {hashPassword,digest} from '../server/auth.js';
import {emptyWorkspace} from '../src/domain/workspace.js';
test('authenticated private workspace and file lifecycle',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'studio-test-'));
 const origin='http://localhost';
 const {server,db}=await createApp({dir,origin,secure:false});
 for(const id of ['alpha','beta'])db.prepare('INSERT INTO users VALUES(?,?,?)').run(id,id,await hashPassword('fictional-test-password'));
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});});
 const base=`http://127.0.0.1:${server.address().port}`;
 let cookie='';
 const call=(path,method='GET',data,extra={})=>fetch(base+path,{method,headers:{Origin:origin,Cookie:cookie,...(data!==undefined?{'Content-Type':'application/json'}:{}),...extra},body:data===undefined?undefined:JSON.stringify(data)});
 assert.equal((await call('/api/workspace')).status,401);
 assert.equal((await call('/server/store.js')).status,404);
 assert.equal((await call('/data/studio.sqlite')).status,404);
 assert.equal((await call('/api/login','POST',{username:'alpha',password:'wrong'})).status,401);
 assert.equal((await call('/api/login','POST',{username:'alpha',password:'fictional-test-password'},{Origin:'https://attacker.invalid'})).status,403);
 let response=await call('/api/login','POST',{username:'alpha',password:'fictional-test-password'});
 assert.equal(response.status,200);
 assert.match(response.headers.get('set-cookie'),/HttpOnly; SameSite=Strict/);
 cookie=response.headers.get('set-cookie').split(';')[0];const alpha=cookie;
 assert.deepEqual(await (await call('/api/workspace')).json(),{revision:0,state:null});
 const state=emptyWorkspace();state.project.name='<img src=x onerror=alert(1)>';
 assert.equal((await call('/api/workspace','PUT',{revision:0,state})).status,200);
 assert.equal((await call('/api/workspace','PUT',{revision:0,state})).status,409);
 assert.equal((await call('/api/workspace','PUT',{revision:1,state:{...state,refs:[{id:'r1',name:'ref',notes:'',images:['javascript:alert(1)']}]}})).status,400);
 response=await fetch(base+'/api/files',{method:'POST',headers:{Origin:origin,Cookie:cookie,'Content-Type':'application/pdf','X-File-Name':'fictional.pdf'},body:'%PDF-1.7\nfictional fixture'});
 assert.equal(response.status,201);const file=await response.json();
 assert.equal((await call(file.url)).status,200);
 assert.match((await call(file.url+'?download')).headers.get('content-disposition'),/attachment/);
 response=await call('/api/login','POST',{username:'beta',password:'fictional-test-password'});cookie=response.headers.get('set-cookie').split(';')[0];
 assert.equal((await call(file.url)).status,404);
 assert.equal((await (await call('/api/workspace')).json()).state,null);
 const forged=emptyWorkspace();forged.contents.push({id:'c1',name:'shoot',time:'',location:'',status:'check',script:true,scriptFile:file.id});
 assert.equal((await call('/api/workspace','PUT',{revision:0,state:forged})).status,400);
 cookie=alpha;
 assert.equal((await (await call('/api/workspace')).json()).state.project.name,state.project.name);
 assert.equal((await call('/api/logout','POST')).status,200);
 assert.equal((await call('/api/workspace')).status,401);
 response=await call('/api/login','POST',{username:'alpha',password:'fictional-test-password'});cookie=response.headers.get('set-cookie').split(';')[0];
 db.prepare('UPDATE sessions SET expires=0 WHERE token=?').run(digest(cookie.split('=')[1]));
 assert.equal((await call('/api/session')).status,401);
});
test('secure cookie and storage survive server restart',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'studio-restart-'));
 let app=await createApp({dir,origin:'https://studio.example.invalid'});
 app.db.prepare('INSERT INTO users VALUES(?,?,?)').run('alpha','alpha',await hashPassword('fictional-test-password'));
 app.db.prepare('INSERT INTO workspaces VALUES(?,?,?)').run('alpha',1,JSON.stringify(emptyWorkspace()));
 await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
 const response=await fetch(`http://127.0.0.1:${app.server.address().port}/api/login`,{method:'POST',headers:{Origin:'https://studio.example.invalid','Content-Type':'application/json'},body:JSON.stringify({username:'alpha',password:'fictional-test-password'})});
 assert.match(response.headers.get('set-cookie'),/; Secure/);
 await new Promise(r=>app.server.close(r));
 app=await createApp({dir,origin:'https://studio.example.invalid'});
 assert.equal(app.db.prepare('SELECT revision FROM workspaces').get().revision,1);
 app.db.close();await rm(dir,{recursive:true,force:true});
});
